def resolve_lang(explicit=None):
    """--lang > THREADS_LANG > ko"""
    for candidate in (explicit, os.getenv("THREADS_LANG")):
        if candidate:
            value = candidate.strip().lower()
            if value in LANGS:
                return value
            raise ValueError(f"지원하지 않는 언어: {candidate} (ko, en, ja 중 하나)")
    return "ko"


